import dotenv from "dotenv";
import pg from "pg";

dotenv.config();

const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL || "";
const supabaseRef = supabaseUrl.match(/^https:\/\/([^.]+)\.supabase\.co$/)?.[1];

const dbConfig = {
  host: process.env.HOST || (supabaseRef ? `db.${supabaseRef}.supabase.co` : undefined),
  port: Number(process.env.PORT || 5432),
  database: process.env.DATABASE || "postgres",
  user: process.env.USER || "postgres",
  password: process.env.POSTGRES || process.env.RAILS_MASTER_KEY,
  ssl: { rejectUnauthorized: false },
  connectionTimeoutMillis: 15000,
};

console.log("dbConfigPresent:", {
  host: Boolean(dbConfig.host),
  port: Boolean(dbConfig.port),
  database: Boolean(dbConfig.database),
  user: Boolean(dbConfig.user),
  password: Boolean(dbConfig.password),
});

const pool = new pg.Pool(dbConfig);

try {
  await pool.query("begin");
  await pool.query(`
    create table if not exists public.codex_connection_test (
      id integer generated by default as identity primary key,
      mensagem text not null
    )
  `);
  const result = await pool.query(
    "insert into public.codex_connection_test (mensagem) values ($1) returning id, mensagem",
    ["teste de conexao criado pelo codex"],
  );
  const count = await pool.query("select count(*)::int as total from public.codex_connection_test");
  await pool.query("commit");
  console.log("createdAndInserted:", result.rows[0]);
  console.log("totalRows:", count.rows[0].total);
} catch (error) {
  try {
    await pool.query("rollback");
  } catch {
    // Ignore rollback failures after connection errors.
  }

  console.log("failed:", {
    name: error.name,
    code: error.code,
    message: error.message,
  });
  process.exitCode = 1;
} finally {
  await pool.end();
}
